import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function start(page: Page, game: string, mode: 'local' | 'ai') {
  await page.locator('.game-card').filter({ hasText: game }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: mode === 'local' ? '同屏对弈' : '人机对弈' }).click()
  await dialog.getByRole('button', { name: '开始对弈' }).click()
  await expect(page.getByRole('heading', { name: game, exact: true })).toBeVisible()
}

const cell = (page: Page, index: number) => page.locator(`button[data-cell="${index}"]`)

