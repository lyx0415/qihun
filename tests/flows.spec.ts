test('四人飞行棋保留自定义规则，退出后仍可轮到其它机队', async ({ page }) => {
  await page.addInitScript(() => { Math.random = () => .03 })
  await page.goto('/')
  await page.locator('.game-card').filter({ hasText: '飞行棋' }).click()
  const setup = page.getByRole('dialog')
  await setup.getByRole('button', { name: '同屏对弈' }).click()
  await setup.getByRole('button', { name: '四人' }).click()
  await setup.getByText('飞行规则设置').click()
  await setup.getByLabel('每队飞机').selectOption('2')
  await setup.getByLabel('起飞点数').selectOption('one-or-six')
  await setup.getByLabel('同色格跳四格').check()
  await setup.getByRole('button', { name: '开始对弈' }).click()
  await expect(page.locator('.flight-seats .player-row')).toHaveCount(4)
  await expect(page.locator('.board .token')).toHaveCount(8)
  await page.getByRole('button', { name: '掷骰', exact: true }).click()
  await expect(page.getByLabel('骰子 1 点')).toBeVisible()
  await cell(page, 16).click()
  await cell(page, 90).click()
  await expect(page.locator('.move-feedback')).toContainText('起飞')
  await expect(page.locator('.player-current')).toContainText('金队')
  await page.reload()
  await expect(page.locator('.flight-seats .player-row')).toHaveCount(4)
  await expect(page.locator('.player-current')).toContainText('金队')
  await page.getByRole('button', { name: '认输', exact: true }).click()
  await page.getByRole('button', { name: '确认退出' }).click()
  await expect(page.locator('.player-current')).toContainText('青队')
  await expect(page.locator('.flight-seats')).toContainText('已退出')
  await expect(page.getByRole('button', { name: '掷骰', exact: true })).toBeEnabled()
})

