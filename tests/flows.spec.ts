test('斗兽棋动物插画可切换，音效风格实测可播放', async ({ page }) => {
  await page.addInitScript(() => {
    const original = AudioContext.prototype.createOscillator
    AudioContext.prototype.createOscillator = function () {
      document.documentElement.dataset.tones = String(Number(document.documentElement.dataset.tones ?? 0) + 1)
      return original.call(this)
    }
  })
  await page.goto('/')
  await start(page, '斗兽棋', 'local')
  await expect(page.locator('.animal-portrait')).toHaveCount(16)
  await page.getByRole('button', { name: '对局设置' }).click()
  const settings = page.getByRole('dialog')
  await settings.getByLabel('斗兽棋棋子').selectOption('text')
  await settings.getByLabel('音效风格').selectOption('soft')
  await settings.getByRole('button', { name: '将军音效', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-tones', '3')
  await settings.getByRole('button', { name: '关闭' }).click()
  await expect(page.locator('.animal-portrait')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.board .token')).toHaveCount(16)
  await expect(page.locator('.animal-portrait')).toHaveCount(0)
})

