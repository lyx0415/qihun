import { expect, test } from '@playwright/test'

test('十九路围棋支持让子、标记、续局和完整终局复盘', async ({ page }) => {
  await page.goto('/#library')
  await page.locator('.game-card').filter({ hasText: '围棋' }).click()
  const setup = page.getByRole('dialog')
  await setup.getByRole('button', { name: '同屏对弈' }).click()
  await setup.getByLabel('棋盘路数').selectOption('19')
  await setup.getByLabel('固定让子').selectOption('3')
  await setup.getByRole('button', { name: '开始对弈' }).click()
  await expect(page.locator('.board .cell')).toHaveCount(361)
  await expect(page.locator('.board .token')).toHaveCount(3)
  const whiteMove = page.waitForResponse(response => response.url().endsWith('/voice/goWhite.wav') && response.ok())
  const middle = page.locator('[data-cell="180"]')
  await middle.click()
  await whiteMove
  await page.reload()
  await expect(page.locator('.board .token')).toHaveCount(4)
  await page.getByRole('button', { name: '停一手' }).click()
  await page.getByRole('button', { name: '停一手' }).click()
  await middle.click()
  await expect(middle).toHaveAccessibleName(/已标记死子/)
  await page.getByRole('button', { name: '确认数子' }).click()
  await expect(page.locator('.go-count-panel')).toContainText('已确认 1/2')
  await page.getByRole('button', { name: '确认数子' }).click()
  await page.getByRole('button', { name: '复盘', exact: true }).click()
  await expect(page.locator('.board .token')).toHaveCount(3)
  await page.getByLabel('复盘速度').selectOption('2')
  await page.getByRole('button', { name: '自动复盘' }).click()
  await expect(page.getByLabel('复盘进度')).toHaveValue('1')
  await page.getByRole('button', { name: '最后一步' }).click()
  await expect(page.locator('.board .dead-point')).toHaveCount(1)
  await expect(page.getByLabel('复盘进度')).toHaveValue('6')
})

test('跑得快十五张使用独立牌谱，墨蓝牌面、清空与普通出牌报音生效', async ({ page }) => {
  await page.goto('/#settings')
  await page.getByLabel('扑克牌面').selectOption('midnight')
  await page.getByRole('navigation').getByRole('button', { name: '牌类' }).click()
  await page.getByRole('button', { name: /跑得快/ }).click()
  const setup = page.getByRole('dialog')
  await setup.getByRole('button', { name: '三人同屏接力' }).click()
  await setup.getByLabel('每手牌数').selectOption('15')
  await setup.getByRole('button', { name: '开始发牌' }).click()
  await expect(page.locator('.deck-midnight')).toBeVisible()
  await page.getByRole('button', { name: '我已接手' }).click()
  await expect(page.locator('.hand-card')).toHaveCount(15)
  const card = page.getByRole('button', { name: '3♠', exact: true })
  await card.click()
  await page.getByRole('button', { name: '清空', exact: true }).click()
  await expect(card).toHaveAttribute('aria-pressed', 'false')
  await card.click()
  const spoken = page.waitForResponse(response => response.url().endsWith('/voice/rank3.wav') && response.ok())
  await page.getByRole('button', { name: '出牌', exact: true }).click()
  await spoken
  await expect(page.locator('.hand-card')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.desk-heading')).toContainText('每手 15 张')
  await expect(page.locator('.deck-midnight')).toBeVisible()
  await expect(page.locator('.played-cards')).toContainText('3')
})

test('仅关键报音抑制普通落子，保留围棋停手', async ({ page }) => {
  const clips: string[] = []
  page.on('request', request => {
    const match = request.url().match(/\/voice\/(\w+)\.wav$/)
    if (match) clips.push(match[1])
  })
  await page.goto('/#settings')
  await page.getByLabel('报音频率').selectOption('key')
  await page.getByRole('navigation').getByRole('button', { name: '棋类' }).click()
  await page.locator('.game-card').filter({ hasText: '围棋' }).click()
  await page.getByRole('dialog').getByRole('button', { name: '同屏对弈' }).click()
  await page.getByRole('button', { name: '开始对弈' }).click()
  await page.locator('[data-cell="40"]').click()
  await expect(page.locator('.board .token')).toHaveCount(1)
  await page.getByRole('button', { name: '停一手' }).click()
  await expect.poll(() => clips.slice()).toContain('goPass')
  expect(clips).not.toContain('goBlack')
  expect(clips).not.toContain('chessStart')
})
